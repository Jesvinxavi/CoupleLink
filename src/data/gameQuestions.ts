// Helper function to filter questions based on spicy mode
export function getFilteredQuestions<T extends { isSpicy: boolean }>(
    questions: T[],
    includeSpicy: boolean
): T[] {
    if (includeSpicy) {
        return questions;
    }
    return questions.filter(q => !q.isSpicy);
}

// Helper function to get random questions
export function getRandomQuestions<T>(questions: T[], count: number): T[] {
    const shuffled = [...questions].sort(() => Math.random() - 0.5);
    return shuffled.slice(0, count);
}
